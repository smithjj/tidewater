// Writes Runtime/World/Fish/FishBehaviour.cs from the BEHAVIOUR table of src/world/Fish.js (the numbers come from the JS source itself).
//   node unity/tools/dump-fish-behaviour.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const src = readFileSync( new URL( '../../src/world/Fish.js', import.meta.url ), 'utf8' );
const grab = ( start ) => {

	const i = src.indexOf( start );
	const a = src.indexOf( '{', i );
	let depth = 0, j = a;
	for ( ; j < src.length; j ++ ) { if ( src[ j ] === '{' ) depth ++; else if ( src[ j ] === '}' && -- depth === 0 ) break; }
	return src.slice( a, j + 1 );

};

const CEILING = - 0.7;
const base = eval( '(' + grab( 'const base = {' ) + ')' );
const table = eval( '(' + grab( 'const BEHAVIOUR = {' ) + ')' );
const d = ( x ) => { const s = String( x ); return s === 'Infinity' ? 'double.PositiveInfinity' : s.includes( '.' ) || s.includes( 'e' ) ? s : s + '.0'; };
const pair = ( p ) => `new[] { ${ d( p[ 0 ] ) }, ${ d( p[ 1 ] ) } }`;
const field = ( k, v ) => Array.isArray( v ) ? `${ k } = ${ pair( v ) }` : typeof v === 'string' ? `${ k } = "${ v }"` : `${ k } = ${ d( v ) }`;
const keys = [ 'cruise', 'max', 'burst', 'accel', 'sep', 'nbr', 'wSep', 'wAli', 'wCoh', 'wGoal', 'flee', 'depth', 'homeRadius', 'amp', 'freq', 'ceiling', 'minDepth', 'band' ];

let out = `// GENERATED by unity/tools/dump-fish-behaviour.mjs from the BEHAVIOUR table of src/world/Fish.js. Do not edit by hand.
// Behaviour per kind of swimmer: model (anatomy of FishSpecies, or "stingray" / "eagleRay" / "turtle"), length range (m), mode (see
// FishSchools.stepGroup), speeds in body lengths / s (cruise, max, burst when fleeing), steering accel, boids (separation distance and
// neighbour radius in body lengths, weights), depth (preferred height above the bottom: fraction of the water column above it), band (water
// depth range of the homes), flee (reaction distance, m), amp / freq (tail beat amplitude and frequency).
using System.Collections.Generic;

namespace Tidewater.World.Fish
{
	public sealed class Behaviour
	{
		public string name, model, mode;
		public double[] length;
		public double ${ keys.filter( ( k ) => ! Array.isArray( base[ k ] ) ).map( ( k ) => `${ k } = ${ d( base[ k ] ) }` ).join( ', ' ) };
		public double[] ${ keys.filter( ( k ) => Array.isArray( base[ k ] ) ).map( ( k ) => `${ k } = ${ pair( base[ k ] ) }` ).join( ', ' ) };
	}

	public static class FishBehaviour
	{
		public static readonly Dictionary<string, Behaviour> BEHAVIOUR = new Dictionary<string, Behaviour>
		{
`;
for ( const [ name, b ] of Object.entries( table ) ) {

	const parts = [ `name = "${ name }"`, field( 'model', b.model ), field( 'mode', b.mode ), field( 'length', b.length ) ];
	for ( const k of keys ) if ( k in b ) parts.push( field( k, b[ k ] ) );
	out += `\t\t\t{ "${ name }", new Behaviour { ${ parts.join( ', ' ) } } },\n`;

}

out += '\t\t};\n\t}\n}\n';
writeFileSync( new URL( '../Assets/Tidewater/Runtime/World/Fish/FishBehaviour.cs', import.meta.url ), out );
console.log( 'FishBehaviour.cs:', Object.keys( table ).length, 'kinds' );
