// Writes Runtime/World/Fish/FishSpecies.cs from src/world/fish/FishSpecies.js (PATTERN, SPECIES, SKIN): the numbers come from the
// JS module itself, so nothing is typed by hand.   node unity/tools/dump-fish-species.mjs
import { PATTERN, SPECIES, SKIN } from '../../src/world/fish/FishSpecies.js';
import { writeFileSync } from 'node:fs';

const d = ( x ) => {

	if ( x === undefined ) return '0';
	const s = String( x );
	return s.includes( '.' ) || s.includes( 'e' ) ? s : s + '.0';

};

const pts = ( a ) => 'new[] { ' + a.map( ( p ) => `new[] { ${ d( p[ 0 ] ) }, ${ d( p[ 1 ] ) } }` ).join( ', ' ) + ' }';
const seg = ( s ) => `new Seg { from = ${ d( s.from ) }, to = ${ d( s.to ) }, rays = ${ s.rays }, spiny = ${ s.spiny }, h = ${ pts( s.h ) }, rake = new[] { ${ d( s.rake[ 0 ] ) }, ${ d( s.rake[ 1 ] ) } }, notch = ${ d( s.notch ) } }`;
const q = ( s ) => JSON.stringify( s );

let out = `// GENERATED by unity/tools/dump-fish-species.mjs from src/world/fish/FishSpecies.js. Do not edit by hand.
// Anatomy of the fish species, normalized to a total length of 1 (snout tip to the tip of the tail fin); see FishSpecies.js for the
// meaning of every field. The rays and the turtle carry only the entries the skin table reads.
using System.Collections.Generic;

namespace Tidewater.World.Fish
{
	public sealed class Mouth { public double corner, y, tip, protrude; }
	public sealed class Eye { public double u, y, r; }
	public sealed class Seg { public double from, to; public int rays; public bool spiny; public double[][] h; public double[] rake; public double notch; }
	public sealed class Paired { public double u, y, len, bas, spread; public int rays; public string shape; }
	public sealed class Caudal { public string shape; public double len, span, fork; public int rays; }
	public sealed class FinletSpec { public double from, to; public int dorsal, ventral; }

	public sealed class Species
	{
		public string name;
		public int pattern;
		public double body, sec;
		public double[][] top, bot, wid;
		public Mouth mouth;
		public Eye eye;
		public double opercle, scales, scaleVis, lateral, arch;
		public Seg[] dorsal, anal;
		public Paired pectoral, pelvic;
		public Caudal caudal;
		public FinletSpec finlets;
		public int iris;
		public double irid, metal;
	}

	// skin colours (sRGB hex): back, flank, belly, fins, fin edges
	public sealed class Skin { public int back, flank, belly, fin, edge; public double rough; }

	public static class FishSpecies
	{
`;

// pattern ids
for ( const k of Object.keys( PATTERN ) ) out += `\t\tpublic const int P_${ k } = ${ PATTERN[ k ] };\n`;
out += `\n\t\tpublic static readonly string[] NAMES = { ${ Object.keys( PATTERN ).sort( ( a, b ) => PATTERN[ a ] - PATTERN[ b ] ).map( q ).join( ', ' ) } };\n\n`;
out += '\t\tpublic static readonly Dictionary<string, Species> SPECIES = new Dictionary<string, Species>\n\t\t{\n';
for ( const [ k, S ] of Object.entries( SPECIES ) ) {

	const m = S.mouth, e = S.eye;
	out += `\t\t\t{ ${ q( k ) }, new Species {\n\t\t\t\tname = ${ q( k ) }, pattern = ${ S.pattern }, body = ${ d( S.body ) }, sec = ${ d( S.sec ) },\n`;
	if ( S.top ) out += `\t\t\t\ttop = ${ pts( S.top ) },\n\t\t\t\tbot = ${ pts( S.bot ) },\n\t\t\t\twid = ${ pts( S.wid ) },\n`;
	out += `\t\t\t\tmouth = new Mouth { corner = ${ d( m.corner ) }, y = ${ d( m.y ) }, tip = ${ d( m.tip ) }, protrude = ${ d( m.protrude ) } },\n`;
	out += `\t\t\t\teye = new Eye { u = ${ d( e.u ) }, y = ${ d( e.y ) }, r = ${ d( e.r ) } }, opercle = ${ d( S.opercle ) },\n`;
	out += `\t\t\t\tscales = ${ d( S.scales ) }, scaleVis = ${ d( S.scaleVis ) }, lateral = ${ d( S.lateral ) }, arch = ${ d( S.arch ) },\n`;
	if ( S.dorsal ) out += `\t\t\t\tdorsal = new[] { ${ S.dorsal.map( seg ).join( ', ' ) } },\n\t\t\t\tanal = new[] { ${ S.anal.map( seg ).join( ', ' ) } },\n`;
	for ( const pk of [ 'pectoral', 'pelvic' ] ) {

		const F = S[ pk ];
		if ( F ) out += `\t\t\t\t${ pk } = new Paired { u = ${ d( F.u ) }, y = ${ d( F.y ) }, len = ${ d( F.len ) }, bas = ${ d( F.base ) }, rays = ${ F.rays }, shape = ${ q( F.shape || '' ) }, spread = ${ d( F.spread ) } },\n`;

	}

	if ( S.caudal ) {

		const C = S.caudal;
		out += `\t\t\t\tcaudal = new Caudal { shape = ${ q( C.shape ) }, len = ${ d( C.len ) }, span = ${ d( C.span ) }, fork = ${ d( C.fork ) }, rays = ${ C.rays } },\n`;

	}

	if ( S.finlets ) {

		const F = S.finlets;
		out += `\t\t\t\tfinlets = new FinletSpec { from = ${ d( F.from ) }, to = ${ d( F.to ) }, dorsal = ${ F.dorsal }, ventral = ${ F.ventral } },\n`;

	}

	out += `\t\t\t\tiris = 0x${ S.iris.toString( 16 ) }, irid = ${ d( S.irid ) }, metal = ${ d( S.metal ) },\n\t\t\t} },\n`;

}

out += '\t\t};\n\n\t\tpublic static readonly Dictionary<string, Skin> SKIN = new Dictionary<string, Skin>\n\t\t{\n';
for ( const [ k, K ] of Object.entries( SKIN ) ) {

	const h = ( x ) => '0x' + x.toString( 16 );
	out += `\t\t\t{ ${ q( k ) }, new Skin { back = ${ h( K.back ) }, flank = ${ h( K.flank ) }, belly = ${ h( K.belly ) }, fin = ${ h( K.fin ) }, edge = ${ h( K.edge ) }, rough = ${ d( K.rough ) } } },\n`;

}

out += '\t\t};\n\t}\n}\n';
writeFileSync( new URL( '../Assets/Tidewater/Runtime/World/Fish/FishSpecies.cs', import.meta.url ), out );
console.log( 'FishSpecies.cs:', out.length, 'bytes,', Object.keys( SPECIES ).length, 'species' );
